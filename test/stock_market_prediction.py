data.head()

"""# Preparing Neural Network"""

X = data["price"].iloc[:-1].values.reshape(-1,1)
y = data["price"].shift(-1).iloc[:-1].values.reshape(-1, 1)

import torch
from torch.utils.data import Dataset, DataLoader

class PriceDataset(Dataset):
    def __init__(self, X, y):
        self.X = X
        self.y = y

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return torch.tensor(self.X[idx], dtype=torch.float32), torch.tensor(self.y[idx], dtype=torch.float32)

import torch.nn as nn

class PricePredictorFF(nn.Module):
    def __init__(self):
        super(PricePredictorFF, self).__init__()
        self.layer = nn.Sequential(
            nn.Linear(1, 64),
            nn.ReLU(),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):
      return self.layer(x)

from sklearn.preprocessing import MinMaxScaler

# Scale the data for better training stability
scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

X_scaled = scaler_X.fit_transform(X)
y_scaled = scaler_y.fit_transform(y)

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y_scaled, test_size=0.2, shuffle=False
)
train_dataset = PriceDataset(X_train, y_train)
test_dataset = PriceDataset(X_test, y_test)

batch_size = 256

train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

import math

epoch = math.ceil(len(train_dataset) / batch_size)
epoch

"""# Define Model"""

import torch.optim as optim

model = PricePredictorFF()
criterion = nn.MSELoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

"""
# Train Model"""

epochs = 10

for epoch in range(epochs):
    model.train()
    epoch_loss = 0.0

    for batch_X, batch_y in train_loader:
        outputs = model(batch_X)
        loss = criterion(outputs, batch_y)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        epoch_loss += loss.item()

    print(f"Epoch {epoch+1}/{epochs}, Loss: {epoch_loss/len(train_loader):.10f}")

"""# Test Model"""

import numpy as np

model.eval()

with torch.no_grad():
    test_losses = []
    all_preds, all_targets = [], []
    for batch_X, batch_y in test_loader:
        preds = model(batch_X)
        loss = criterion(preds, batch_y)
        test_losses.append(loss.item())

        all_preds.append(preds.numpy())
        all_targets.append(batch_y.numpy())

        # Compute batch loss
        loss = criterion(preds, batch_y)
        test_losses.append(loss.item())

    print(f"Average Test Loss: {sum(test_losses)/len(test_losses):.10f}")


all_preds = np.vstack(all_preds)
all_targets = np.vstack(all_targets)

predictions_rescaled = scaler_y.inverse_transform(all_preds)
y_test_rescaled = scaler_y.inverse_transform(all_targets)

print(f"Average Test Loss (scaled): {sum(test_losses)/len(test_losses):.10f}")

